import io
import random
import urllib.parse
import httpx
from pyrogram import filters, types

from MeowRobot import pbot as bot
from MeowRobot.utils.fonts import font

__mod_name__ = "Imagine"
__module__ = "𝐀𝐈 𝐀ʀᴛ🎨"

__help__ = """
*AI Image Generation Module🎨*

*Commands:*  
❂ `/imagine [prompt]` — Generate stunning AI artwork from text prompt  
❂ `/generate [prompt]` — Same as `/imagine`  

*Example:*  
`/imagine cute cybernetic cat with neon headphones in futuristic tokyo`
"""

@bot.on_message(filters.command(["imagine", "generate"]) & ~filters.forwarded)
async def imagine_art(_, m: types.Message):
    if len(m.command) < 2:
        return await m.reply_text(font("❌ Usage: `/imagine [description of image]`"))

    prompt = m.text.split(None, 1)[1].strip()
    status_msg = await m.reply_text(font("🎨 Creating your masterpiece... please wait a moment."))

    safe_prompt = urllib.parse.quote(prompt)
    seed = random.randint(1, 9999999)
    url = f"https://image.pollinations.ai/prompt/{safe_prompt}?width=1024&height=1024&seed={seed}&nologo=true"

    try:
        async with httpx.AsyncClient(timeout=45.0, follow_redirects=True) as client:
            resp = await client.get(url)
            if resp.status_code == 200 and resp.content:
                image_bytes = io.BytesIO(resp.content)
                image_bytes.name = "imagine.jpg"

                caption = (
                    f"✨ **AI Generated Artwork**\n\n"
                    f"📝 **Prompt:** `{prompt}`\n"
                    f"👤 **Generated by:** {m.from_user.mention if m.from_user else 'User'}\n\n"
                    f"♨️ **Powered by:** @TheAloneTeam"
                )

                await m.reply_photo(
                    photo=image_bytes,
                    caption=caption
                )
                await status_msg.delete()
                return

        await status_msg.edit_text(font("❌ Failed to generate artwork. Please try a different prompt!"))
    except Exception as e:
        await status_msg.edit_text(font(f"❌ Error generating image: {e}"))
